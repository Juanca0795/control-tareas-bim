/* Vinculación Gantt (fase 1): catálogo fijo del Excel de noviembre, sin lectura de OneDrive desde el navegador.
   La vinculación NO altera el PPC operativo ni la fecha límite del entregable. */
function normalizeGanttLinks(input){
  const links={};
  if(!input||typeof input!=='object'||Array.isArray(input))return links;
  for(const [taskId,row] of Object.entries(input)){
    if(!taskId||!row||typeof row!=='object'||Array.isArray(row))continue;
    const mode=['select','manual','none'].includes(row.mode)?row.mode:'none';
    const updatedAt=typeof row.updatedAt==='string'&&Number.isFinite(Date.parse(row.updatedAt))
      ?row.updatedAt:'1970-01-01T00:00:00.000Z';
    const activityId=String(row.activityId||'').trim().slice(0,40);
    const group=String(row.group||'').trim().slice(0,120);
    const name=String(row.name||'').trim().slice(0,180);
    if(mode==='none'){links[taskId]={mode:'none',activityId:'',group:'',name:'',updatedAt};continue;}
    if(mode==='select'&&!activityId)continue;
    if(mode==='manual'&&(!group||!name))continue;
    links[taskId]={mode,activityId,group,name,updatedAt};
  }
  return links;
}
function mergeGanttLinks(remote,local){
  const merged=normalizeGanttLinks(remote);
  for(const [id,row] of Object.entries(normalizeGanttLinks(local))){
    if(!merged[id]||row.updatedAt>=merged[id].updatedAt)merged[id]=row;
  }
  return merged;
}
function ganttText(value){
  return String(value||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'')
    .toLocaleLowerCase('es').replace(/[^a-z0-9]+/g,' ').trim().replace(/\s+/g,' ');
}
function ganttActivityById(id){
  return window.BIM_GANTT_ACTIVITIES.find(a=>a.id===id)||null;
}
function ganttLinkedTask(activity,excludeId){
  if(!activity||activity.mode==='none')return null;
  return tasks.find(t=>{
    if(t.id===excludeId)return false;
    const prior=catalogs.ganttLinksByTask?.[t.id];
    if(!prior||prior.mode==='none')return false;
    if(activity.activityId&&prior.activityId)return activity.activityId===prior.activityId;
    return ganttText(prior.group)===ganttText(activity.group)&&ganttText(prior.name)===ganttText(activity.name);
  })||null;
}
/* Equivalencias explícitas entre colaboradores de ÁREA BIM y responsables del Gantt.
   La asignación se basa en el nombre normalizado, no en el texto visible del grupo. */
function ganttResponsibleForOwner(owner){
  const normalized=ganttText(owner);
  const words=normalized.split(' ').filter(Boolean);
  const has=word=>words.includes(word);
  if(!normalized)return '';
  // Orden importante: identificar primero a los integrantes del equipo de Cova.
  if((has('juan')&&has('cova'))||(has('arnold')&&has('cova'))||
     has('naysha')||has('ivan')||has('ivana')||has('pedro')||normalized==='cova')
    return 'Juan Carlos Cova';
  if(has('roger')||has('diana'))return 'Roger Cabrera';
  if(has('oriol'))return 'Oriol Huera Diaz';
  if(has('claudio'))return 'Claudio Villano';
  if(has('prada')||(has('juan')&&has('carlos')&&has('torres')))
    return 'Juan Carlos Prada';
  return '';
}
function ganttGroups(responsible=''){
  return [...new Set(window.BIM_GANTT_ACTIVITIES
    .filter(a=>a.owner===responsible).map(a=>a.group))]
    .sort((a,b)=>a.localeCompare(b,'es',{numeric:true}));
}
